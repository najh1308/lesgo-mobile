-- Rancangan keamanan:
-- * Semua tabel memakai Row Level Security tanpa policy, jadi aplikasi TIDAK
--   bisa membaca/menulis tabel secara langsung dengan publishable key.
-- * Aplikasi hanya boleh memanggil fungsi api_* (web service lewat RPC).
--   Setiap fungsi memeriksa token login sendiri (bukan Supabase Auth).
-- * Password di-hash dengan bcrypt (pgcrypto). Token login disimpan
--   sebagai hash SHA-256, jadi kebocoran tabel tidak membocorkan token.
-- * Fungsi bantu ada di skema "internal" yang tidak dibuka ke internet.
--
-- File ini aman dijalankan ulang, TETAPI akan menghapus semua data lama.
