-- Melempar error dengan kode status HTTP di "hint" agar aplikasi bisa membedakannya.
create function internal.gagal(p_status int, p_pesan text, p_errors jsonb default null)
returns void language plpgsql as $$
begin
  raise exception using message = p_pesan, hint = p_status::text,
                        detail = coalesce(p_errors::text, '');
end $$;

create function internal.waktu_wib(t timestamptz) returns text
language sql stable as $$ select to_char(t at time zone 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS') $$;

create function internal.hash_token(p_token text) returns text
language sql immutable as $$ select encode(extensions.digest(p_token, 'sha256'), 'hex') $$;

-- Validasi token lalu kembalikan data pengguna. Dipakai oleh semua fungsi yang butuh login.
create function internal.user_dari_token(p_token text) returns public.users
language plpgsql stable as $$
declare u public.users;
begin
  if p_token is null or p_token = '' then
    perform internal.gagal(401, 'Token tidak ditemukan. Silakan login.');
  end if;
  select us.* into u
  from public.auth_tokens t join public.users us on us.id = t.user_id
  where t.token_hash = internal.hash_token(p_token) and t.expired_at > now();
  if not found then
    perform internal.gagal(401, 'Sesi berakhir. Silakan login lagi.');
  end if;
  return u;
end $$;

-- Data pengguna yang aman dikirim ke aplikasi (tanpa hash password).
create function internal.public_user(u public.users) returns jsonb
language sql immutable as $$
  select jsonb_build_object(
    'id', u.id, 'nama', u.nama, 'email', u.email, 'no_hp', u.no_hp,
    'foto_base64', u.foto_base64,
    'mata_uang_pref', u.mata_uang_pref, 'zona_waktu_pref', u.zona_waktu_pref)
$$;

-- Rumus haversine (km) untuk LBS.
create function internal.jarak_km(lat1 float8, lng1 float8, lat2 float8, lng2 float8)
returns float8 language sql immutable as $$
  select 6371 * 2 * atan2(sqrt(a), sqrt(1 - a))
  from (select sin(radians(lat2 - lat1) / 2) ^ 2
             + cos(radians(lat1)) * cos(radians(lat2)) * sin(radians(lng2 - lng1) / 2) ^ 2 as a) x
$$;

-- Daftar mapel unik sebuah bimbel, mis. 'Fisika, IPA, Matematika'.
create function internal.mapel_bimbel(p_bimbel_id bigint) returns text
language sql stable as $$
  select string_agg(distinct trim(m), ', ' order by trim(m))
  from public.program p, unnest(string_to_array(p.mapel, ',')) m
  where p.bimbel_id = p_bimbel_id
$$;

create function internal.jadwal_program(p_program_id bigint) returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', j.id, 'hari', j.hari,
      'jam_mulai', to_char(j.jam_mulai, 'HH24:MI'), 'jam_selesai', to_char(j.jam_selesai, 'HH24:MI'),
      'tanggal_mulai', j.tanggal_mulai::text,
      'kuota', j.kuota, 'terisi', j.terisi, 'sisa', greatest(0, j.kuota - j.terisi))
    order by j.tanggal_mulai, j.jam_mulai), '[]'::jsonb)
  from public.jadwal j where j.program_id = p_program_id
$$;

create function internal.program_dengan_jadwal(p_bimbel_id bigint) returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', p.id, 'nama_program', p.nama_program, 'jenjang', p.jenjang, 'mapel', p.mapel,
      'mode', p.mode, 'harga_idr', p.harga_idr, 'durasi_minggu', p.durasi_minggu,
      'deskripsi', p.deskripsi, 'jadwal', internal.jadwal_program(p.id))
    order by p.harga_idr), '[]'::jsonb)
  from public.program p where p.bimbel_id = p_bimbel_id
$$;

create function internal.pendaftaran_json(d public.pendaftaran) returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'id', d.id, 'status', d.status, 'total_idr', d.total_idr, 'metode_bayar', d.metode_bayar,
    'created_at', internal.waktu_wib(d.created_at),
    'program', jsonb_build_object('id', p.id, 'nama_program', p.nama_program, 'jenjang', p.jenjang,
                                  'mapel', p.mapel, 'mode', p.mode, 'durasi_minggu', p.durasi_minggu),
    'bimbel', jsonb_build_object('id', b.id, 'nama', b.nama, 'alamat', b.alamat, 'kota', b.kota),
    'jadwal', jsonb_build_object('id', j.id, 'hari', j.hari,
                                 'jam_mulai', to_char(j.jam_mulai, 'HH24:MI'),
                                 'jam_selesai', to_char(j.jam_selesai, 'HH24:MI'),
                                 'tanggal_mulai', j.tanggal_mulai::text))
  from public.program p
  join public.bimbel b on b.id = p.bimbel_id
  join public.jadwal j on j.id = d.jadwal_id
  where p.id = d.program_id
$$;

-- ---------- Blockchain sederhana ----------

create function internal.hitung_hash(p_index int, p_pendaftaran_id bigint, p_data text,
                                     p_prev text, p_waktu timestamp, p_nonce int)
returns text language sql immutable as $$
  select encode(extensions.digest(concat_ws('|', p_index, p_pendaftaran_id, p_data, p_prev,
                to_char(p_waktu, 'YYYY-MM-DD HH24:MI:SS'), p_nonce), 'sha256'), 'hex')
$$;

-- Tambah block baru dengan proof-of-work sederhana (hash harus diawali "00").
create function internal.tambah_block(p_pendaftaran_id bigint, p_data jsonb) returns jsonb
language plpgsql as $$
declare
  v_last  record;
  v_index int := 1;
  v_prev  text := repeat('0', 64);
  v_waktu timestamp(0) := (now() at time zone 'Asia/Jakarta')::timestamp(0);
  v_data  text := p_data::text;
  v_nonce int := 0;
  v_hash  text;
begin
  perform pg_advisory_xact_lock(7001); -- satu penulis rantai dalam satu waktu
  select block_index, hash into v_last from public.blockchain_log order by block_index desc limit 1;
  if found then
    v_index := v_last.block_index + 1;
    v_prev := v_last.hash;
  end if;
  loop
    v_hash := internal.hitung_hash(v_index, p_pendaftaran_id, v_data, v_prev, v_waktu, v_nonce);
    exit when left(v_hash, 2) = '00';
    v_nonce := v_nonce + 1;
  end loop;
  insert into public.blockchain_log (block_index, pendaftaran_id, data, prev_hash, hash, nonce, created_at)
  values (v_index, p_pendaftaran_id, v_data, v_prev, v_hash, v_nonce, v_waktu);
  return jsonb_build_object('block_index', v_index, 'hash', v_hash);
end $$;

