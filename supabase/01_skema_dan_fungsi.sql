          'mapel', mapel_bimbel(b.id),
          'is_favorit', true) as j
      from favorit f join bimbel b on b.id = f.bimbel_id join program p on p.bimbel_id = b.id
      where f.user_id = u.id
      group by b.id) x);
end $$;

create or replace function public.api_favorit_set(p_token text, p_bimbel_id bigint, p_aktif boolean)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare u users := user_dari_token(p_token);
begin
  if p_aktif then
    if not exists (select 1 from bimbel where id = p_bimbel_id) then perform gagal(404, 'Bimbel tidak ditemukan'); end if;
    insert into favorit (user_id, bimbel_id) values (u.id, p_bimbel_id) on conflict do nothing;
    return jsonb_build_object('pesan', 'Ditambahkan ke favorit');
  end if;
  delete from favorit where user_id = u.id and bimbel_id = p_bimbel_id;
  return jsonb_build_object('pesan', 'Dihapus dari favorit');
end $$;

-- ---------- Pendaftaran & blockchain ----------

create or replace function public.api_pendaftaran_create(p_token text, p_program_id bigint, p_jadwal_id bigint,
                                              p_metode_bayar text default 'transfer')
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  u users := user_dari_token(p_token);
  v_metode text := trim(coalesce(p_metode_bayar, 'transfer'));
  v_j record;
  d pendaftaran;
  v_block jsonb;
begin
  if v_metode not in ('transfer', 'e-wallet', 'tunai') then perform gagal(422, 'Metode pembayaran tidak dikenal'); end if;

  -- Kunci baris jadwal agar kuota tidak terlampaui jika dua orang daftar bersamaan.
  select j.id, j.kuota, j.terisi, p.harga_idr into v_j
  from jadwal j join program p on p.id = j.program_id
  where j.id = p_jadwal_id and j.program_id = p_program_id
  for update of j;
  if not found then perform gagal(404, 'Program atau jadwal tidak ditemukan'); end if;
  if v_j.terisi >= v_j.kuota then perform gagal(409, 'Kuota jadwal ini sudah penuh'); end if;
  if exists (select 1 from pendaftaran where user_id = u.id and jadwal_id = p_jadwal_id
             and status in ('menunggu','aktif')) then
    perform gagal(409, 'Kamu sudah terdaftar di jadwal ini');
  end if;

  insert into pendaftaran (user_id, program_id, jadwal_id, total_idr, metode_bayar, status)
  values (u.id, p_program_id, p_jadwal_id, v_j.harga_idr, v_metode, 'aktif')
  returning * into d;
  update jadwal set terisi = terisi + 1 where id = p_jadwal_id;

  v_block := tambah_block(d.id, jsonb_build_object(
    'event', 'DAFTAR', 'pendaftaran_id', d.id, 'user_id', u.id,
    'program_id', p_program_id, 'jadwal_id', p_jadwal_id, 'total_idr', v_j.harga_idr));

  return jsonb_build_object('pesan', 'Pendaftaran berhasil', 'pendaftaran', pendaftaran_json(d), 'block', v_block);
end $$;

