create table public.users (
  id              bigint generated by default as identity primary key,
  nama            text not null,
  email           text not null unique,
  password_hash   text not null,
  no_hp           text not null,
  foto_base64     text,
  mata_uang_pref  text not null default 'IDR' check (mata_uang_pref in ('IDR','USD','EUR','JPY')),
  zona_waktu_pref text not null default 'WIB' check (zona_waktu_pref in ('WIB','WITA','WIT','LONDON')),
  created_at      timestamptz not null default now()
);

create table public.auth_tokens (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  expired_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index on public.auth_tokens (user_id);

create table public.bimbel (
  id         bigint generated by default as identity primary key,
  nama       text not null,
  alamat     text not null,
  kota       text not null,
  latitude   numeric(10,7) not null,
  longitude  numeric(10,7) not null,
  deskripsi  text,
  kontak     text,
  jam_buka   text,
  foto       text,
  rating_avg numeric(2,1) not null default 0.0,
  created_at timestamptz not null default now()
);

create table public.program (
  id            bigint generated by default as identity primary key,
  bimbel_id     bigint not null references public.bimbel(id) on delete cascade,
  nama_program  text not null,
  jenjang       text not null check (jenjang in ('SD','SMP','SMA','UTBK')),
  mapel         text not null,
  mode          text not null default 'offline' check (mode in ('offline','online')),
  harga_idr     integer not null check (harga_idr >= 0),
  durasi_minggu integer not null default 4,
  deskripsi     text
);
create index on public.program (bimbel_id);

create table public.jadwal (
  id            bigint generated by default as identity primary key,
  program_id    bigint not null references public.program(id) on delete cascade,
  hari          text not null,
  jam_mulai     time not null,   -- WIB
  jam_selesai   time not null,   -- WIB
  tanggal_mulai date not null,
  kuota         integer not null default 20,
  terisi        integer not null default 0
);
create index on public.jadwal (program_id);

create table public.pendaftaran (
  id           bigint generated by default as identity primary key,
  user_id      bigint not null references public.users(id) on delete cascade,
  program_id   bigint not null references public.program(id),
  jadwal_id    bigint not null references public.jadwal(id),
  total_idr    integer not null,
  metode_bayar text not null default 'transfer',
  status       text not null default 'aktif' check (status in ('menunggu','aktif','batal','selesai')),
  created_at   timestamptz not null default now()
);
create index on public.pendaftaran (user_id);

-- Satu rantai block untuk seluruh sistem. Block lama tidak pernah diubah;
-- pembatalan dicatat sebagai block baru.
create table public.blockchain_log (
  id             bigint generated by default as identity primary key,
  block_index    integer not null unique,
  pendaftaran_id bigint not null references public.pendaftaran(id),
  data           text not null,
  prev_hash      text not null,
  hash           text not null,
  nonce          integer not null default 0,
  created_at     timestamp(0) not null  -- WIB, ikut dihitung dalam hash
