-- Kunci semua tabel: RLS aktif tanpa policy + cabut hak akses langsung.
do $$
declare t text;
begin
  foreach t in array array['users','auth_tokens','bimbel','program','jadwal','pendaftaran',
                           'blockchain_log','favorit','review','skor_game','saran_kesan'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

