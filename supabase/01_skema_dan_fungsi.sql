-- Validasi seluruh rantai (bukan hanya milik pengguna).
create or replace function public.api_blockchain_validate(p_token text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  b record;
  v_prev text := repeat('0', 64);
  v_urutan int := 1;
  v_total int := 0;
  v_rusak jsonb := '[]'::jsonb;
  v_alasan text;
  v_hitung text;
begin
  perform user_dari_token(p_token);
  for b in select * from blockchain_log order by block_index loop
    v_alasan := null;
    if b.block_index <> v_urutan then
      v_alasan := 'Nomor block tidak berurutan';
    elsif b.prev_hash <> v_prev then
      v_alasan := 'Hash sebelumnya tidak cocok';
    else
      v_hitung := hitung_hash(b.block_index, b.pendaftaran_id, b.data, b.prev_hash, b.created_at, b.nonce);
      if v_hitung <> b.hash or left(v_hitung, 2) <> '00' then v_alasan := 'Isi block telah berubah'; end if;
    end if;
    if v_alasan is not null then
      v_rusak := v_rusak || jsonb_build_array(jsonb_build_object('block_index', b.block_index, 'alasan', v_alasan));
    end if;
    v_prev := b.hash;
    v_urutan := v_urutan + 1;
    v_total := v_total + 1;
  end loop;
  return jsonb_build_object('valid', jsonb_array_length(v_rusak) = 0, 'total_block', v_total, 'block_rusak', v_rusak);
end $$;

