-- ---------- Autentikasi & profil ----------

create or replace function public.api_register(p_nama text, p_email text, p_no_hp text, p_password text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
  v_errors jsonb := '{}'::jsonb;
begin
  if trim(coalesce(p_nama, '')) = '' then v_errors := v_errors || '{"nama":"Nama wajib diisi"}'; end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then v_errors := v_errors || '{"email":"Format email tidak valid"}'; end if;
  if coalesce(trim(p_no_hp), '') !~ '^[0-9+]{9,15}$' then v_errors := v_errors || '{"no_hp":"Nomor HP tidak valid"}'; end if;
  if length(coalesce(p_password, '')) < 6 then v_errors := v_errors || '{"password":"Password minimal 6 karakter"}'; end if;
  if v_errors <> '{}'::jsonb then perform gagal(422, 'Data belum valid', v_errors); end if;

  if exists (select 1 from users where email = v_email) then
    perform gagal(422, 'Email sudah terdaftar', '{"email":"Email sudah terdaftar"}');
  end if;

  -- Password di-hash bcrypt, tidak pernah disimpan sebagai teks asli.
  insert into users (nama, email, password_hash, no_hp)
  values (trim(p_nama), v_email, crypt(p_password, gen_salt('bf', 10)), trim(p_no_hp));
  return jsonb_build_object('pesan', 'Akun berhasil dibuat. Silakan masuk.');
end $$;

create or replace function public.api_login(p_email text, p_password text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  u users;
  v_token text;
  v_exp timestamptz := now() + interval '7 days';
begin
  select * into u from users where email = lower(trim(coalesce(p_email, '')));
  if not found or u.password_hash <> crypt(coalesce(p_password, ''), u.password_hash) then
    perform gagal(401, 'Email atau password salah');
  end if;

  delete from auth_tokens where expired_at < now(); -- bersih-bersih token kedaluwarsa
  v_token := encode(gen_random_bytes(32), 'hex');
  insert into auth_tokens (user_id, token_hash, expired_at) values (u.id, hash_token(v_token), v_exp);
  return jsonb_build_object('token', v_token, 'expired_at', waktu_wib(v_exp), 'user', public_user(u));
end $$;

create or replace function public.api_logout(p_token text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
begin
  delete from auth_tokens where token_hash = hash_token(coalesce(p_token, ''));
  return jsonb_build_object('pesan', 'Berhasil keluar');
end $$;

create or replace function public.api_me(p_token text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
begin
  return public_user(user_dari_token(p_token));
end $$;

create or replace function public.api_update_me(p_token text, p_nama text default null, p_no_hp text default null,
                                     p_mata_uang text default null, p_zona text default null)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  u users := user_dari_token(p_token);
  v_nama text := trim(coalesce(p_nama, u.nama));
  v_hp   text := trim(coalesce(p_no_hp, u.no_hp));
  v_uang text := upper(coalesce(p_mata_uang, u.mata_uang_pref));
  v_zona text := upper(coalesce(p_zona, u.zona_waktu_pref));
begin
  if v_nama = '' then perform gagal(422, 'Nama wajib diisi'); end if;
  if v_uang not in ('IDR','USD','EUR','JPY') then perform gagal(422, 'Mata uang tidak didukung'); end if;
  if v_zona not in ('WIB','WITA','WIT','LONDON') then perform gagal(422, 'Zona waktu tidak didukung'); end if;
  update users set nama = v_nama, no_hp = v_hp, mata_uang_pref = v_uang, zona_waktu_pref = v_zona
  where id = u.id returning * into u;
  return public_user(u);
end $$;

-- Foto profil disimpan sebagai base64 (aplikasi sudah memperkecil gambarnya).
create or replace function public.api_set_foto(p_token text, p_foto_base64 text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  u users := user_dari_token(p_token);
  v_bytes bytea;
begin
  if p_foto_base64 is null or p_foto_base64 = '' then perform gagal(422, 'File foto tidak ditemukan'); end if;
  if length(p_foto_base64) > 700000 then perform gagal(422, 'Ukuran foto maksimal sekitar 500 KB'); end if;
  begin
    v_bytes := decode(p_foto_base64, 'base64');
  exception when others then
    perform gagal(422, 'Data foto rusak');
  end;
  if not (substring(v_bytes from 1 for 3) = '\xffd8ff'::bytea          -- JPG
          or substring(v_bytes from 1 for 4) = '\x89504e47'::bytea     -- PNG
          or substring(v_bytes from 1 for 4) = '\x52494646'::bytea) then -- WEBP (RIFF)
    perform gagal(422, 'Format foto harus JPG, PNG, atau WEBP');
  end if;
  update users set foto_base64 = p_foto_base64 where id = u.id returning * into u;
  return public_user(u);
end $$;

create or replace function public.api_ubah_password(p_token text, p_lama text, p_baru text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare u users := user_dari_token(p_token);
begin
  if u.password_hash <> crypt(coalesce(p_lama, ''), u.password_hash) then
    perform gagal(422, 'Password lama salah', '{"password_lama":"Password lama salah"}');
  end if;
  if length(coalesce(p_baru, '')) < 6 then
    perform gagal(422, 'Password baru minimal 6 karakter', '{"password_baru":"Minimal 6 karakter"}');
  end if;
  update users set password_hash = crypt(p_baru, gen_salt('bf', 10)) where id = u.id;
  return jsonb_build_object('pesan', 'Password berhasil diubah');
end $$;

