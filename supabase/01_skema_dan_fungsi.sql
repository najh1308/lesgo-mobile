  values (u.id, p_skor, greatest(1, coalesce(p_level, 1)), greatest(0, coalesce(p_durasi, 0)));
  return jsonb_build_object('pesan', 'Skor tersimpan');
end $$;

-- 10 skor terbaik, satu skor terbaik per pengguna.
create or replace function public.api_game_leaderboard(p_token text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
begin
  perform user_dari_token(p_token);
  return (
    select coalesce(jsonb_agg(jsonb_build_object('peringkat', x.peringkat, 'nama', x.nama, 'skor', x.skor)
                              order by x.peringkat), '[]'::jsonb)
    from (select row_number() over (order by max(s.skor) desc, min(s.created_at)) as peringkat,
                 us.nama, max(s.skor) as skor
          from skor_game s join users us on us.id = s.user_id
          group by us.id, us.nama
          order by skor desc limit 10) x);
end $$;

create or replace function public.api_saran_kesan_kirim(p_token text, p_saran text, p_kesan text)
