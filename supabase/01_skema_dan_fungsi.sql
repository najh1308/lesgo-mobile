create or replace function public.api_review_add(p_token text, p_bimbel_id bigint, p_rating int, p_komentar text default '')
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare u users := user_dari_token(p_token);
begin
  if p_rating is null or p_rating not between 1 and 5 then perform gagal(422, 'Rating harus 1 sampai 5'); end if;
  -- Review hanya boleh dari pengguna yang pernah mendaftar di bimbel ini.
  if not exists (select 1 from pendaftaran d join program p on p.id = d.program_id
                 where d.user_id = u.id and p.bimbel_id = p_bimbel_id and d.status in ('aktif','selesai')) then
    perform gagal(403, 'Review hanya untuk pengguna yang sudah mendaftar');
  end if;
  insert into review (user_id, bimbel_id, rating, komentar)
  values (u.id, p_bimbel_id, p_rating, trim(coalesce(p_komentar, '')))
  on conflict (user_id, bimbel_id) do update set rating = excluded.rating, komentar = excluded.komentar;
  update bimbel set rating_avg = (select round(avg(rating), 1) from review where bimbel_id = p_bimbel_id)
  where id = p_bimbel_id;
  return jsonb_build_object('pesan', 'Review tersimpan');
end $$;

create or replace function public.api_favorit_list(p_token text)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare u users := user_dari_token(p_token);
begin
  return (
    select coalesce(jsonb_agg(x.j order by x.waktu desc), '[]'::jsonb) from (
      select max(f.created_at) as waktu, jsonb_build_object(
          'id', b.id, 'nama', b.nama, 'alamat', b.alamat, 'kota', b.kota,
