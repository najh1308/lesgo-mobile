create or replace function public.api_pendaftaran_batal(p_token text, p_id bigint)
returns jsonb language plpgsql security definer set search_path = public, extensions, internal as $$
declare
  u users := user_dari_token(p_token);
  d pendaftaran;
begin
  select * into d from pendaftaran where id = p_id and user_id = u.id for update;
  if not found then perform gagal(404, 'Pendaftaran tidak ditemukan'); end if;
  if d.status not in ('menunggu', 'aktif') then perform gagal(409, 'Pendaftaran ini tidak bisa dibatalkan'); end if;

  update pendaftaran set status = 'batal' where id = p_id returning * into d;
  update jadwal set terisi = greatest(0, terisi - 1) where id = d.jadwal_id;
  -- Block lama tidak boleh diubah, jadi pembatalan dicatat sebagai block baru.
  perform tambah_block(p_id, jsonb_build_object('event', 'BATAL', 'pendaftaran_id', p_id, 'user_id', u.id));
  return pendaftaran_json(d);
end $$;

